const env = { ...process.env, DLYA_DEV_DATA_DIR:folder };
delete env.ELECTRON_RUN_AS_NODE;
let app;
async function launch() {
  app = await electron.launch({args:[path.resolve(__dirname,'..')],env});
  const window = await app.firstWindow();
  await window.getByRole('heading',{name:'Новая смена — чистый лист'}).or(window.getByRole('dialog')).waitFor();
  return window;
}

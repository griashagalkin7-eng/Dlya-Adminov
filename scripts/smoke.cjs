  assert.equal(await window.locator('.payment-total.transfer strong').innerText(),'540 ₽');
  assert.equal(await window.locator('.metric.pc strong').innerText(),'500 ₽');
  assert.equal(await window.getByTestId('admin-month-amount').innerText(),'123 ₽');
  await window.getByRole('button',{name:'Учёт',exact:true}).click();
  await window.getByRole('button',{name:'Начать учёт',exact:true}).first().click();
  modal=window.getByRole('dialog');
  await modal.getByLabel('Дата учёта').fill('2026-11-19');
  await modal.getByRole('button',{name:'День',exact:true}).click();
  await modal.getByRole('button',{name:'Начать учёт',exact:true}).click();
  await window.getByRole('button',{name:'ПК',exact:true}).click();
  await window.getByLabel('Сумма, ₽',{exact:true}).fill('770');
  await window.getByRole('button',{name:'Наличка',exact:true}).click();
  await window.getByRole('status').filter({hasText:'Позиция добавлена'}).waitFor();
  assert.equal(await window.getByTestId('admin-day-amount').innerText(),'200 ₽');
  await window.getByRole('button',{name:'Статистика',exact:true}).click();

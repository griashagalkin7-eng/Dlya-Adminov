// Optional UI check using the real Electron app and an isolated temporary ledger.
const { _electron: electron } = require('playwright');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const ExcelJS = require('exceljs');
const folder = fs.mkdtempSync(path.join(os.tmpdir(),'dlya-ui-'));
const screenshots = process.env.DLYA_SCREENSHOT_DIR;
const env = { ...process.env, DLYA_DEV_DATA_DIR:folder };
delete env.ELECTRON_RUN_AS_NODE;
let app;
async function launch() {
  app = await electron.launch({args:[path.resolve(__dirname,'..')],env});
  const window = await app.firstWindow();
  await window.getByRole('heading',{name:'Новая смена — чистый лист'}).or(window.getByRole('dialog')).waitFor();
  return window;
}
(async () => {
  let window = await launch();
  const errors = [];
  window.on('pageerror',error => errors.push(error.message));
  await window.getByRole('button',{name:'Настройки',exact:true}).click();
  await window.getByRole('button',{name:'Добавить',exact:true}).first().click();
  let modal = window.getByRole('dialog');
  await modal.getByLabel('Название',{exact:true}).fill('Вода 0,5 л');
  await modal.getByLabel('Исходная цена, ₽').fill('105');
  await modal.getByRole('button',{name:'Сохранить',exact:true}).click();
  const discountPanel = window.locator('.settings-discount');
  await discountPanel.getByLabel('Скидка, %').fill('10');
  await discountPanel.getByRole('button',{name:'Сохранить'}).click();
  await window.getByRole('button',{name:'Учёт',exact:true}).click();
  await window.getByRole('button',{name:'Начать учёт',exact:true}).first().click();
  modal = window.getByRole('dialog');
  await modal.getByLabel('Дата учёта').fill('2026-11-19');
  await modal.getByRole('button',{name:'Ночь',exact:true}).click();
  await modal.getByRole('button',{name:'Начать учёт',exact:true}).click();
  await window.getByRole('textbox',{name:'Поиск товара'}).fill('Вод');
  await window.locator('.suggestions').getByRole('button').first().click();
  await window.getByLabel('Количество',{exact:true}).fill('2');
  await window.getByRole('button',{name:'Добавить',exact:true}).click();
  await window.getByRole('button',{name:'PS / услуги',exact:true}).click();
  await window.getByLabel('Услуга / описание').fill('ТВ3 — 1,5 часа');
  await window.getByLabel('Сумма, ₽',{exact:true}).fill('550');
  await window.getByRole('button',{name:'Дисконт 10%',exact:true}).click();
  await window.getByRole('button',{name:'Добавить',exact:true}).click();
  await window.getByRole('cell',{name:'ТВ3 — 1,5 часа',exact:true}).waitFor();
  assert.equal(await window.locator('.metric.total strong').innerText(),'685 ₽');
  if(screenshots) {
    fs.mkdirSync(screenshots,{recursive:true});
    await window.getByRole('status').waitFor({state:'hidden'});
    await window.screenshot({path:path.join(screenshots,'Dlya-Adminov-light.png'),fullPage:true});
    await window.getByRole('button',{name:'Тёмная тема'}).click();
    await window.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
    await window.waitForTimeout(250); // Let the button color transitions finish before capturing.
    await window.screenshot({path:path.join(screenshots,'Dlya-Adminov-dark.png'),fullPage:true});
    await window.getByRole('button',{name:'Светлая тема'}).click();
    await window.waitForFunction(() => document.documentElement.dataset.theme === 'light');
    await window.waitForTimeout(250);
  }
  await window.getByRole('button',{name:'Открыть отчёт',exact:true}).click();
  const exportFile = path.join(folder,'report.xlsx');
  await app.evaluate(({dialog},file) => {dialog.showSaveDialog = async () => ({canceled:false,filePath:file});},exportFile);
  await window.getByRole('button',{name:'Скачать XLSX',exact:true}).click();
  await window.getByRole('status').filter({hasText:'Отчёт сохранён'}).waitFor();
  const book = new ExcelJS.Workbook(); await book.xlsx.readFile(exportFile);
  assert.equal(book.worksheets[0].getCell(`F${book.worksheets[0].rowCount}`).value,685);
  await window.getByRole('button',{name:'Вернуться в учёт',exact:true}).click();
  await app.close();
  app = undefined;
  window = await launch();
  modal = window.getByRole('dialog');
  await modal.getByRole('button',{name:'Продолжить учёт',exact:true}).click();
  assert.equal(await window.locator('.metric.total strong').innerText(),'685 ₽');
  await window.getByRole('button',{name:'Открыть отчёт',exact:true}).click();
  await window.getByRole('button',{name:'Завершить учёт',exact:true}).click();
  await window.getByRole('dialog').getByRole('button',{name:'Завершить учёт',exact:true}).click();
  await window.getByRole('heading',{name:'Новая смена — чистый лист'}).waitFor();
  await window.getByRole('button',{name:'История',exact:true}).click();
  await window.getByRole('button',{name:'Открыть отчёт',exact:true}).click();
  await window.getByRole('button',{name:'Редактировать',exact:true}).click();
  await window.getByRole('button',{name:'Редактировать: ТВ3 — 1,5 часа',exact:true}).click();
  modal = window.getByRole('dialog');
  await modal.getByLabel('Сумма до дисконта, ₽').fill('600');
  await modal.getByRole('button',{name:'Сохранить',exact:true}).click();
  await modal.waitFor({state:'hidden'});
  assert.equal(await window.locator('.metric.total strong').innerText(),'730 ₽');
  await window.getByRole('button',{name:'Статистика',exact:true}).click();
  await window.getByLabel('Месяц',{exact:true}).fill('2026-11');
  assert.equal(await window.locator('.metric.total strong').innerText(),'730 ₽');
  assert.deepEqual(errors,[]);
  console.log('UI passed: settings, product search, PS discount, XLSX, restart, finish, history edit and statistics.');
})().catch(error => { console.error(error);process.exitCode=1; }).finally(async () => { if(app)await app.close(); fs.rmSync(folder,{recursive:true,force:true}); });
